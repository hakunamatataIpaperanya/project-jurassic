  function rasterize(markup, detail) {
    const g = detail ? `<g fill="none" stroke="#fff" stroke-width="1.1" stroke-linecap="round" stroke-linejoin="round">${markup}</g>` : `<g ${BODY}>${markup}</g>`;
    const src = `<svg xmlns="http://www.w3.org/2000/svg" width="${MW}" height="${MH}" viewBox="${VB.join(" ")}"><style>.f{fill:#fff;stroke:none}</style>${g}</svg>`;
    return new Promise((res, rej) => {
      const im = new Image();
      im.onload = () => res(im);
      im.onerror = rej;
      im.src = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(src);
    });
  }

  async function inflate(mask) {
    // SOR บนพิกเซลในรูปร่าง (ขอบภาพเป็น 0 เสมอ) — แบ่งทำเป็นช่วง ๆ คืนเวลาให้เบราว์เซอร์วาดภาพระหว่างช่วง (ไม่กระตุก)
    const idx = [];
    for (let y = 1; y < MH - 1; y++) for (let x = 1; x < MW - 1; x++) if (mask[y * MW + x]) idx.push(y * MW + x);
    const u = new Float32Array(MW * MH), I = Int32Array.from(idx), om = 1.92;
    let t0 = performance.now();
    for (let it = 0; it < 260; it++) {
      for (let j = 0; j < I.length; j++) {
        const i = I[j], v = (u[i - 1] + u[i + 1] + u[i - MW] + u[i + MW] + 1) * 0.25;
        u[i] += om * (v - u[i]);
      }
      if (performance.now() - t0 > 8) {
        await new Promise((r) => setTimeout(r, 0));
        t0 = performance.now();
      }
    }
    const z = new Float32Array(MW * MH);
    for (let j = 0; j < I.length; j++) z[I[j]] = Math.sqrt(2 * Math.max(0, u[I[j]]));
    return { idx: I, z };
  }

  async function build(key, dens = 1, look = "") {
    // look = "clear": หน้าทายชื่อซาก — วงสแกนแนวนอนน้อยลง เส้นรอบตัวหนาแน่นขึ้น (รูปร่างชัด ไม่ลายตา); หน้าแรกใช้แบบเดิม
    const clear = look === "clear";
    const s = SHAPES[key] || SHAPES.slab, depth = s.depth ?? 0.85, spread = s.spread ?? 0.6;
    const cv = document.createElement("canvas");
    cv.width = MW; cv.height = MH;
    const ctx = cv.getContext("2d", { willReadFrequently: true });
    const mask = async (markup, detail) => {
      const im = await rasterize(markup, detail);
      ctx.clearRect(0, 0, MW, MH);
      ctx.drawImage(im, 0, 0);
      const a = ctx.getImageData(0, 0, MW, MH).data, m = new Uint8Array(MW * MH);
      for (let i = 0; i < m.length; i++) m[i] = a[i * 4 + 3] > 110 ? 1 : 0;
      return m;
    };
    const layers = [];
    const spec = [["far", s.far, 1, 1], ["body", s.body, 1, 0], ["near", s.near, 1, -1],
      ["thin", s.thin, 0.15, 0], ["farThin", s.farThin, 0.15, 1], ["nearThin", s.nearThin, 0.15, -1]];
    for (const [name, mk, dm, side] of spec) {
      if (!mk) continue;
      const m = await mask(mk), inf = await inflate(m);
      layers.push({ name, m, dm, side, ...inf });
    }
    const body = layers.find((l) => l.name === "body");
    let zb = 0;
    for (let j = 0; j < body.idx.length; j++) zb = Math.max(zb, body.z[body.idx[j]]);
    for (const l of layers) { l.off = l.side * spread * zb * depth; l.k = depth * l.dm; l.b = l.dm < 1 ? 0.55 : 1; }   // ชั้นบาง: จุดซ้อนกันในระนาบเดียว จึงหรี่ลง

    // ขอบเขตของรูปร่าง (พิกเซล)
    let x0 = MW, x1 = 0, y0 = MH, y1 = 0, area = 0;
    for (const l of layers) for (let j = 0; j < l.idx.length; j++) {
      const i = l.idx[j], x = i % MW, y = (i / MW) | 0;
      if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
    }
    for (const l of layers) area += l.idx.length;
    const cx = (x0 + x1) / 2, cy = (y0 + y1) / 2, pts = [], nrm = [];
    // ทิศของผิว (normal) ต่อจุด สำหรับแสงเงา: ผิว z = ±k·f(x, y) -> n = (−k·fx, −k·fy, ±1); ขอบรูปร่าง -> n ในระนาบภาพ
    const push = (x, y, z, b, k, nx = 0, ny = 0, nz = 0) => {
      const l = Math.hypot(nx, ny, nz) || 1;
      pts.push((x - cx) / SC, (y - cy) / SC, z / SC, b, k);
      nrm.push(nx / l, ny / l, nz / l);
    };
    const grad = (l, i) => [((l.z[i + 1] - l.z[i - 1]) / 2) * l.k, ((l.z[i + MW] - l.z[i - MW]) / 2) * l.k];
    const budget = (window.innerWidth < 700 ? 0.7 : 1) * dens;   // จอเล็ก (มือถือ) ใช้จุดน้อยลง; dens = ความหนาแน่นที่ผู้เรียกขอ
    // 1) ผิว: สุ่มตามพื้นที่ผิวจริง (ด้านข้างที่ชันได้จุดมากขึ้น)
    const NS = 4200 * budget;
    for (const l of layers) {
      const want = Math.round((NS * l.idx.length) / area);
      for (let got = 0, guard = 0; got < want && guard < want * 30; guard++) {
        const i = l.idx[(Math.random() * l.idx.length) | 0];
        const gx = ((l.z[i + 1] - l.z[i - 1]) / 2) * l.k, gy = ((l.z[i + MW] - l.z[i - MW]) / 2) * l.k;
        if (Math.random() * 4 > Math.min(4, Math.sqrt(1 + gx * gx + gy * gy))) continue;
        const side = Math.random() < 0.5 ? -1 : 1;
        push((i % MW) + Math.random() - 0.5, ((i / MW) | 0) + Math.random() - 0.5, side * l.z[i] * l.k + l.off, 0.55 * l.b, 0, -gx, -gy, side);
        got++;
      }
    }
    // 2) วงสแกนแนวนอน (ตัดเป็นชั้น ๆ เหมือนเครื่องสแกน 3 มิติ)
    const NR = 2200 * budget * (s.rings ?? 1) * (clear ? 0.4 : 1), xs = 2, ky = Math.max(4, Math.round((area * 2) / xs / NR));
    for (const l of layers) for (let y = y0 + (ky >> 1); y <= y1; y += ky) for (let x = x0; x <= x1; x += xs) {
      const i = y * MW + x;
      if (!l.m[i]) continue;
      const [gx, gy] = grad(l, i);
      push(x, y, l.z[i] * l.k + l.off, 0.7 * l.b, 1, -gx, -gy, 1);
      push(x, y, -l.z[i] * l.k + l.off, 0.7 * l.b, 1, -gx, -gy, -1);
    }
    // 3) ขอบรูปร่าง (เส้นรอบตัวที่ความลึกกลางของแต่ละชั้น)
    const edges = [];
    for (const l of layers) for (let j = 0; j < l.idx.length; j++) {
      const i = l.idx[j];
      if (!l.m[i - 1] || !l.m[i + 1] || !l.m[i - MW] || !l.m[i + MW]) {
        // ขอบที่อยู่ในเนื้อของส่วนอื่น (เช่น โคนขาที่ซ้อนลำตัว) ไม่ใช่ขอบนอกของตัวสัตว์ -> หรี่ลง ไม่ให้เป็นวงเส้นสว่างกลางตัว
        const inner = layers.some((q) => q !== l && q.dm === 1 && q.m[i]);
        edges.push([i, l.off, l.b * (inner ? (clear ? 0.12 : 0.3) : 1), l.m[i - 1] - l.m[i + 1], l.m[i - MW] - l.m[i + MW]]);
      }
    }
    const es = Math.max(clear ? 1 : 2, Math.round(edges.length / ((clear ? 2600 : 1000) * budget)));
    for (let j = 0; j < edges.length; j += es) push(edges[j][0] % MW, (edges[j][0] / MW) | 0, edges[j][1], 0.9 * edges[j][2], 2, edges[j][3], edges[j][4], 0);   // ไปทางด้านที่ว่าง (นอกรูปร่าง)
    // 4) เส้นรายละเอียด (ตา ฟัน ซี่เปลือก) บนผิวทั้งสองด้าน
    if (s.detail) {
      const dm = await mask(s.detail, true), dl = [];
      for (let i = 0; i < dm.length; i++) if (dm[i]) dl.push(i);
      const dk = s.dk ?? 1, db = dk > 1 ? 1.7 : 1, ds = Math.max(dk > 1 ? 1 : 3, Math.round(dl.length / (420 * dk * budget)));
      const order = ["near", "nearThin", "body", "thin", "far", "farThin"].map((n) => layers.find((l) => l.name === n)).filter(Boolean);
      for (let j = 0; j < dl.length; j += ds) {
        const i = dl[j], l = order.find((q) => q.m[i]), x = i % MW, y = (i / MW) | 0;
        if (!l) { push(x, y, 0, db, 3); continue; }
        const [gx, gy] = grad(l, i);
        push(x, y, l.z[i] * l.k + l.off - 0.6, db, 3, -gx, -gy, 1);
        push(x, y, -l.z[i] * l.k + l.off + 0.6, db, 3, -gx, -gy, -1);
      }
    }
    // วางเอียง (ภาพที่วาดจากด้านบน เช่น ไทรโลไบต์ ปู รอยตีน)
    const n = pts.length / 5;
    if (s.tilt) {
      const c = Math.cos(s.tilt), sn = Math.sin(s.tilt);
      for (let j = 0; j < n; j++) {
        const y = pts[j * 5 + 1], z = pts[j * 5 + 2], ny = nrm[j * 3 + 1], nz = nrm[j * 3 + 2];
        pts[j * 5 + 1] = y * c - z * sn;
        pts[j * 5 + 2] = y * sn + z * c;
        nrm[j * 3 + 1] = ny * c - nz * sn;
        nrm[j * 3 + 2] = ny * sn + nz * c;
      }
    }
    let minX = 1e9, maxX = -1e9, minY = 1e9, maxY = -1e9, minZ = 1e9, maxZ = -1e9;
    for (let j = 0; j < n; j++) {
      const x = pts[j * 5], y = pts[j * 5 + 1], z = pts[j * 5 + 2];
      minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
      minZ = Math.min(minZ, z); maxZ = Math.max(maxZ, z);
    }
    const midY = (minY + maxY) / 2, h = maxY - minY, w = maxX - minX, d = maxZ - minZ;
    const P = new Float32Array(n * 7);
    for (let j = 0; j < n; j++) {
      const y = pts[j * 5 + 1] - midY;
      P.set([pts[j * 5], y, pts[j * 5 + 2], pts[j * 5 + 3], pts[j * 5 + 4], (maxY - midY - y) / h, Math.random()], j * 7);
    }
    const bottom = maxY - midY;
    return { P, N: Float32Array.from(nrm), n, w, h, d, bottom, ground: bottom + h * (s.float ? 0.14 : 0.025), R: Math.max(0.3 * w, 0.28 * h, 0.5 * d, 24) };
  }

  const model = (key, dens = 1, look = "") => {
    const id = `${key}@${dens}${look}`;
    if (!MODELS.has(id)) MODELS.set(id, build(key, dens, look));
    return MODELS.get(id);
  };

  function sprite(rgb) {
    const c = document.createElement("canvas");
    c.width = c.height = 32;
    const g = c.getContext("2d"), gr = g.createRadialGradient(16, 16, 0, 16, 16, 16);
    gr.addColorStop(0, `rgba(${rgb},1)`);
    gr.addColorStop(0.14, `rgba(${rgb},0.9)`);
    gr.addColorStop(0.4, `rgba(${rgb},0.28)`);
    gr.addColorStop(1, `rgba(${rgb},0)`);
    g.fillStyle = gr;
    g.fillRect(0, 0, 32, 32);
    return c;
  }
  let SPR = null;

  function run(box, m, opt = {}) {
    const view = !!opt.view;
    // วาดทุกเฟรม: หมุนตามเมาส์ / นิ้ว (ไม่แตะ = แกว่งช้า ๆ) + ภาพปรากฏจากแท่น + แถบสแกน + กะพริบ / สัญญาณรบกวน + ฝุ่นแสงลอยขึ้น
    SPR = SPR || { c: sprite("24,209,255"), h: sprite("175,242,255"), r: sprite("255,70,120"), b: sprite("80,140,255"), d: sprite("20,96,170") };
    const cv = box.querySelector(".holo-cv"), ctx = cv.getContext("2d");
    const glow = document.createElement("canvas"), gctx = glow.getContext("2d");
    const reduce = matchMedia("(prefers-reduced-motion: reduce)").matches;
    const dpr = Math.min(2, window.devicePixelRatio || 1);
    let W = 0, H = 0, visible = true, raf = 0, stopped = false;
    const resize = () => {
      W = cv.width = Math.round(cv.clientWidth * dpr);
      H = cv.height = Math.round(cv.clientHeight * dpr);
      glow.width = Math.max(1, W >> 2); glow.height = Math.max(1, H >> 2);
    };
    resize();
    const ro = new ResizeObserver(resize);
    ro.observe(cv);
    const io = new IntersectionObserver((e) => (visible = e[0].isIntersecting));
    io.observe(cv);
    const t0 = performance.now();
    let yaw = reduce ? 0.5 : -0.9, pitch = 0.22, last = t0;
    let glitchAt = t0 + 6000 + Math.random() * 6000, glitchEnd = 0, gY = 0, gH = 0, gS = 0;
    const dust = Array.from({ length: 22 }, () => [(Math.random() * 2 - 1) * m.R * 1.2, m.ground - Math.random() * m.h * 1.3, (Math.random() * 2 - 1) * m.R * 1.2, 0.4 + Math.random() * 0.6]);
    const P = m.P, N = m.N;
    const LX = -0.46, LY = -0.56, LZ = -0.69;          // แสงหลักจากซ้ายบนด้านหน้า (พิกัดกล้อง: y ลง, z ห่างกล้อง)

    function stop() {
      stopped = true;
      cancelAnimationFrame(raf);
      ro.disconnect();
      io.disconnect();
    }

    function frame(now) {
      if (stopped) return;
      if (!cv.isConnected) return stop();
      raf = requestAnimationFrame(frame);
      if (!visible || !W || !H) return;
      const t = (now - t0) / 1000, dt = Math.min(0.05, (now - last) / 1000);
      last = now;
      const ptr = box._ptr || {};
      const tYaw = ptr.active ? ptr.x * 2.6 : reduce ? 0.5 : 0.55 * Math.sin(t * 0.42 + 0.3) + 0.1;
      const tPitch = ptr.active ? Math.max(-0.12, Math.min(0.6, 0.22 - ptr.y * 0.6)) : 0.22;
      const ease = 1 - Math.pow(0.0015, dt);
      yaw += (tYaw - yaw) * ease;
      pitch += (tPitch - pitch) * ease;
      const cY = Math.cos(yaw), sY = Math.sin(yaw), cP = Math.cos(pitch), sP = Math.sin(pitch);
      // ตัวสัตว์เต็มกรอบมากขึ้น (เดิม 50% ของความสูง) และอยู่ต่ำกว่าป้ายชื่อด้านบนเล็กน้อย
      const scale = Math.min((W * (view ? 0.84 : 0.86)) / Math.max(m.w, m.d * 0.8), (H * (view ? 0.72 : 0.64)) / m.h), Fz = W * 1.7;
      const cx = W / 2, cy = H * (view ? 0.52 : 0.56) - (m.ground - m.bottom) * scale * 0.5, zr = Math.max(m.w, m.d) / 2;
      const proj = (x, y, z, out) => {
        const x1 = x * cY + z * sY, z1 = -x * sY + z * cY, y1 = y * cP - z1 * sP, z2 = y * sP + z1 * cP;
        const k = Fz / (Fz + z2 * scale);
        out[0] = cx + x1 * scale * k; out[1] = cy + y1 * scale * k; out[2] = z2; out[3] = k;
        return out;
      };
      const q = [0, 0, 0, 0];
      const ps = view ? Math.max(1, Math.min(2.6, W / (640 * dpr), H / (330 * dpr))) : 1;   // กรอบขยายดู: จุดใหญ่ตามขนาดกรอบ (ไม่ให้ภาพโปร่งเป็นจุด ๆ)
      ctx.globalCompositeOperation = "source-over";
      ctx.clearRect(0, 0, W, H);
      ctx.globalCompositeOperation = "lighter";

      // แท่นฉาย: แสงนวลบนพื้น + วงแหวน (วงประหมุน)
      proj(0, m.ground, 0, q);
      const fx = q[0], fy = q[1], fr = m.R * scale;
      ctx.save();
      ctx.translate(fx, fy);
      ctx.scale(1, Math.max(0.12, Math.abs(sP)));
      const fg = ctx.createRadialGradient(0, 0, 0, 0, 0, fr * 1.25);
      fg.addColorStop(0, "rgba(24,209,255,0.42)");
      fg.addColorStop(0.55, "rgba(24,209,255,0.10)");
      fg.addColorStop(1, "rgba(24,209,255,0)");
      ctx.fillStyle = fg;
      ctx.globalAlpha = 1;
      ctx.beginPath(); ctx.arc(0, 0, fr * 1.25, 0, Math.PI * 2); ctx.fill();
      ctx.restore();
      const rings = [[1, 150, 0, 0.5], [0.78, 64, t * 0.35, 0.65], [0.52, 90, -t * 0.6, 0.45], [0.26, 40, 0, 0.6]];
      for (const [rr, cnt, ph, al] of rings) for (let j = 0; j < cnt; j++) {
        if (rr === 0.78 && j % 4 === 3) continue;
        const a = ph + (j / cnt) * Math.PI * 2;
        proj(Math.cos(a) * m.R * rr, m.ground, Math.sin(a) * m.R * rr, q);
        const sz = 5 * dpr * q[3] * ps;
        ctx.globalAlpha = al * (0.6 + 0.4 * (0.5 - q[2] / (2 * m.R)));
        ctx.drawImage(SPR.c, q[0] - sz, q[1] - sz, sz * 2, sz * 2);
      }

      // ขอบบนของภาพ (ใช้กำหนดช่วงของแถบสัญญาณรบกวน); ไม่วาดลำแสงรูปสี่เหลี่ยมคางหมูจากแท่น (ผู้ใช้ขอเอาออก)
      const topY = cy - (m.h / 2) * scale * 1.05;

      // สัญญาณรบกวน (glitch) เป็นช่วง ๆ
      if (!reduce && now > glitchAt) {
        glitchEnd = now + 80 + Math.random() * 160;
        gY = topY + Math.random() * (fy - topY); gH = (6 + Math.random() * 26) * dpr; gS = (Math.random() < 0.5 ? -1 : 1) * (4 + Math.random() * 12) * dpr;
        glitchAt = now + 7000 + Math.random() * 8000;
      }
      const glitch = now < glitchEnd;
      const flick = reduce ? 1 : (0.9 + 0.06 * Math.sin(t * 21) + 0.04 * Math.sin(t * 7.7)) * (glitch ? 0.75 : 1);
      const band = reduce ? -1e9 : topY + (((t * 0.32) % 1.25) / 1.0) * (fy - topY);
      const boot = reduce ? 99 : t;

      // ตัวภาพ
      // ผิว = จุดใหญ่จาง (เนื้อเรียบ), วงสแกน = จาง, ขอบรูปร่าง = จุดเล็กสว่าง (เส้นรอบตัวคม), รายละเอียด (ตา ฟัน) = ชัด
      const sizes = [5, 3.4, 2.8, 3.2], alphas = [0.16, 0.06, 0.4, 0.3];
      for (let j = 0; j < m.n; j++) {
        const o = j * 7;
        let x = P[o], y = P[o + 1], z = P[o + 2], fade = 1;
        if (boot < 2.4) {
          const pp = (boot - (0.12 + 0.95 * P[o + 5] + 0.22 * P[o + 6])) / 0.55;
          if (pp <= 0) continue;
          if (pp < 1) {
            const e = 1 - Math.pow(1 - pp, 3);
            x *= 0.12 + 0.88 * e; z *= 0.12 + 0.88 * e; y = m.ground + (y - m.ground) * e;
            fade = (0.35 + 0.65 * pp) * (1 + 1.6 * (1 - pp));
          }
        }
        proj(x, y, z, q);
        const kind = P[o + 4];
        // แสงเงา: ผิวที่หันหากล้องรับแสงตามมุม + ขอบเรือง (fresnel) / ผิวด้านหลังมองทะลุได้แต่จาง -> เห็นเป็นก้อน 3 มิติ
        const nx = N[j * 3], ny = N[j * 3 + 1], nz = N[j * 3 + 2];
        const nx1 = nx * cY + nz * sY, nz1 = -nx * sY + nz * cY, ny1 = ny * cP - nz1 * sP, nz2 = ny * sP + nz1 * cP, face = -nz2;
        const rim = Math.pow(1 - Math.min(1, Math.abs(face)), 2.2), diff = Math.max(0, nx1 * LX + ny1 * LY + nz2 * LZ);
        const lit = kind === 2 ? 1.15 : face >= 0 ? 0.22 + 0.78 * diff + 0.9 * rim : 0.2 + 0.45 * rim;
        let a = alphas[kind] * P[o + 3] * 2.1 * lit * flick * fade * (0.35 + 0.65 * Math.min(1, Math.max(0, 0.5 - q[2] / (2 * zr))));
        let spr = kind === 3 || lit > 1.05 ? SPR.h : lit < 0.38 ? SPR.d : SPR.c;
        if (Math.abs(q[1] - band) < 3 * dpr) { a *= 1.7; spr = SPR.h; }
        let sx = q[0];
        if (glitch && q[1] > gY && q[1] < gY + gH) {
          sx += gS;
          const s2 = sizes[kind] * dpr * q[3] * ps;
          ctx.globalAlpha = Math.min(1, a * 0.8);
          ctx.drawImage(SPR.r, sx + 3 * dpr - s2, q[1] - s2, s2 * 2, s2 * 2);
          ctx.drawImage(SPR.b, sx - 3 * dpr - s2, q[1] - s2, s2 * 2, s2 * 2);
        }
        const sz = sizes[kind] * dpr * q[3] * ps;
        ctx.globalAlpha = Math.min(1, a);
        ctx.drawImage(spr, sx - sz, q[1] - sz, sz * 2, sz * 2);
      }

      // ฝุ่นแสงลอยขึ้นจากแท่น
      for (const p of dust) {
        if (!reduce) { p[1] -= dt * 9 * p[3]; if (p[1] < m.ground - m.h * 1.35) p[1] = m.ground; }
        proj(p[0], p[1], p[2], q);
        const life = Math.min(1, (m.ground - p[1]) / (m.h * 0.2)) * Math.min(1, (p[1] - (m.ground - m.h * 1.35)) / (m.h * 0.3));
        const sz = 3.4 * dpr * q[3] * ps;
        ctx.globalAlpha = 0.35 * p[3] * Math.max(0, life);
        ctx.drawImage(SPR.h, q[0] - sz, q[1] - sz, sz * 2, sz * 2);
      }

      // แสงเรือง (bloom): ย่อภาพลงแล้วขยายกลับ ซ้อนแบบบวกแสง
      gctx.globalCompositeOperation = "source-over";
      gctx.clearRect(0, 0, glow.width, glow.height);
      gctx.drawImage(cv, 0, 0, glow.width, glow.height);
      ctx.globalAlpha = 0.25;                            // แสงเรืองพอดี ไม่ให้ขอบรูปร่างฟุ้ง
      ctx.drawImage(glow, 0, 0, W, H);
      ctx.globalAlpha = 1;
    }
    raf = requestAnimationFrame(frame);
    return stop;
  }

  function attachPointer(box) {
    // ตำแหน่งเมาส์ / นิ้วบนกรอบภาพ (ใช้ทั้งแบบ 3D และภาพสำรอง 2D)
    if (box._ptr) return;
    box._ptr = { x: 0, y: 0, active: false };
    const set = (rx, ry, gx, gy) => {
      box.style.setProperty("--rx", `${rx}deg`); box.style.setProperty("--ry", `${ry}deg`);
      box.style.setProperty("--gx", `${gx}%`); box.style.setProperty("--gy", `${gy}%`);
    };
    box.addEventListener("pointermove", (e) => {
      const r = box.getBoundingClientRect(), x = (e.clientX - r.left) / r.width - 0.5, y = (e.clientY - r.top) / r.height - 0.5;
      Object.assign(box._ptr, { x, y, active: true });
      box.classList.add("live");
      set((-y * 20).toFixed(1), (x * 30).toFixed(1), ((x + 0.5) * 100).toFixed(0), ((y + 0.5) * 100).toFixed(0));
    });
    box.addEventListener("pointerleave", () => {
      box._ptr.active = false;
      box.classList.remove("live");
      set(0, 0, 50, 30);
    });
  }

  function show(box, key, hud, opt = {}) {
    // แสดง hologram ในกรอบ: 3D จุดแสงถ้าเบราว์เซอร์รองรับ ไม่งั้นใช้ภาพ 2D
    //   opt.view = กรอบขยายดู (ตัวใหญ่ขึ้น จุดหนาแน่นขึ้น)
    if (box._stop) box._stop();
    box._stop = null;
    attachPointer(box);
    const token = (box._token = {});
    box.classList.remove("boot", "holo2d", "holo3d");
    const flat = () => {
      box.classList.remove("holo3d");
      box.classList.add("holo2d");
      box.innerHTML = stage(key, hud);
      fit(box.querySelector(".holo-svg"));
      void box.offsetWidth;
      box.classList.add("boot");
    };
    if (!window.ResizeObserver || !window.IntersectionObserver || !document.createElement("canvas").getContext) return flat();
    box.classList.add("holo3d");
    box.innerHTML = `<div class="holo-grid"></div><canvas class="holo-cv" role="img" aria-label="${hud.aria || ""}"></canvas>${hudHTML(key, hud)}`;
    model(key, opt.view ? 1.5 : 1, "clear").then((m) => { if (box._token === token) box._stop = run(box, m, opt); })
      .catch(() => { if (box._token === token) flat(); });
  }

