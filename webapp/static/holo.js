  // -> หน้าตัดกลมตามความกว้างเฉพาะที่ (ขาเป็นท่อกลม ลำตัวอ้วน) จากนั้นโรยจุดแสงบนผิว + วงสแกนแนวนอน + ขอบ + เส้นรายละเอียด
  const SC = 2, VB = [-40, -50, 320, 240], MW = VB[2] * SC, MH = VB[3] * SC;
